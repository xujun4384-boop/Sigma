def ids():
    return list(STYLES.keys())


def get(style_id):
    return STYLES.get((style_id or "").strip())


def label(style_id):
    s = get(style_id)
    return s["label"] if s else ""


def menu():
    """给编导看的风格菜单：一句话说清“什么时候用”，以及这条风格里人物该怎么用。"""
    lines = []
    for sid in DEFAULT_ORDER:
        s = STYLES[sid]
        usage = (s.get("actor") or {}).get("usage", "")
        tail = f'｜人物{usage}' if usage else ""
        lines.append(f'- {sid}（{s["label"]}）：适合 {("、".join(s["use_for"]))}；'
                     f'不适合 {("、".join(s["avoid_for"]))}{tail}')
    return "\n".join(lines)


def prompt(style_id, context="lyric"):
    """把一种风格展开成可直接照做的提示词段落。

    context:
      - "lyric"  → 给歌词 MV 用：带推荐歌词版式；
      - "styled" → 给导演组的 styled 单段动画用：无歌词，去掉版式建议，
                   actor 皮肤保留（同一套 stage 引擎）。
    """
    s = get(style_id)
    if not s:
        return ""
    v, c = s["visual"], s["character"]
    act = s.get("actor") or {}
    actor_line = ""
    if act:
        actor_line = (f"- 引擎皮肤：{act.get('skin', 'flat')}；{act.get('treat', '')}\n")
        if act.get("usage"):
            actor_line += f"- {act['usage']}\n"
    lyric_line = ""
    if context == "lyric":
        lyric_line = f"- 推荐歌词版式：{' / '.join(s['lyric'])}（整片只用一种，由编导定）\n"
    return f"""### 本片视觉风格：{s['label']}（{style_id}）
时代/题材：{"、".join(s['era'])}｜适合：{"、".join(s['use_for'])}｜不适合：{"、".join(s['avoid_for'])}
配色：{v['palette']}
线条：{v['line']}
质感：{v['texture']}
光：{v['light']}
构图：{v['composition']}
运动：{v['motion']}
道具写法：{s['prop']}
文字：{TEXT_STYLES.get(style_id, '短标题/标签/数字可以写；不要歌词/旁白原文，不要长段落')}；必须与背景高对比（浅底深字/深底浅字），必要时加描边或半透明底板
禁止：{"；".join(s['forbidden'])}

#### 人物（可选：只有画面需要时才用）
- 画法：{c['can']}；{c['head']}；{c['body']}；{c['limbs']}
- 细节：{c['face']}；{c['hair']}；{c['cloth']}；{c['joints']}；{c['motion']}
{actor_line}{lyric_line}"""


def spec_hash(style_id):
    """风格的稳定指纹：用于导演组的分段签名，风格库内容变了也能触发重渲。"""
    s = get(style_id)
    if not s:
        return ""
    raw = json.dumps(s, ensure_ascii=False, sort_keys=True, default=str)
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()[:16]


def summary(style_id):
    s = get(style_id)
    if not s:
        return ""
    return f"{s['label']}：{s['visual']['palette']}；人物：{s['character']['head']}"
